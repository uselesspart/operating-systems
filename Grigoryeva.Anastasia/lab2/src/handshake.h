// Двустороннее знакомство (handshake) с помощью сигнала SIGUSR1.
//   1. Клиент знает pid хоста (аргумент командной строки) и посылает ему SIGUSR1.
//   2. Хост через siginfo узнаёт pid клиента, выдаёт ему id в сессии, создаёт ресурсы соединения
//      и отвечает сигналом SIGUSR1 (sigqueue), в значении которого передан id (либо -1 - отказ).
//   3. Клиент синхронно ждёт ответ (тайм-аут 5 c), получает id и открывает ресурсы соединения.
#pragma once

#include <sys/types.h>

#include <string>

// Блокирует SIGUSR1 в вызывающем потоке (и во всех потоках, созданных после этого).
// Вызывать самым первым действием в main, до создания потоков.
void BlockHandshakeSignal();

// --- сторона хоста ---
// Ждёт запрос знакомства до timeoutMs. true - получен (pid клиента в clientPid).
bool HostWaitRequest(int timeoutMs, pid_t& clientPid);
// Отправляет клиенту ответ с id (id <= 0 означает отказ).
bool HostReply(pid_t clientPid, int id);

// --- сторона клиента ---
// Возвращает id клиента (> 0) или -1 (описание в err). Тайм-аут общий: timeoutMs.
// Запрос повторяется каждые ~1.5 c (стандартные сигналы могут слипаться); хост отвечает на повторы идемпотентно.
int ClientHandshake(pid_t hostPid, int timeoutMs, std::string& err);
